function mc(
  id: string,
  topicSlug: GrammarExercise['topicSlug'],
  lessonSlug: string,
  prompt: string,
  options: Array<{ id: string; label: string }>,
  optionId: string,
  explanation: string,
  sortOrder: number,
): GrammarExercise {
  return {
    id,
    topicSlug,
    lessonSlug,
    type: 'multiple_choice',
    prompt,
    explanation,
    sortOrder,
    contentSchemaVersion: EXERCISE_CONTENT_SCHEMA_VERSION,
    payload: { options },
    answer: { optionId },
  };
}

function fill(
  id: string,
  topicSlug: GrammarExercise['topicSlug'],
  lessonSlug: string,
  prompt: string,
  template: string,
  accepted: string[],
  explanation: string,
  sortOrder: number,
): GrammarExercise {
  return {
    id,
    topicSlug,
    lessonSlug,
    type: 'fill_blank',
    prompt,
    explanation,
    sortOrder,
    contentSchemaVersion: EXERCISE_CONTENT_SCHEMA_VERSION,
    payload: { template },
    answer: { accepted },
  };
}

function order(
  id: string,
  topicSlug: GrammarExercise['topicSlug'],
  lessonSlug: string,
  prompt: string,
  tokens: Array<{ id: string; text: string }>,
  tokenIds: string[],
  explanation: string,
  sortOrder: number,
): GrammarExercise {
  return {
    id,
    topicSlug,
    lessonSlug,
    type: 'sentence_order',
    prompt,
    explanation,
    sortOrder,
    contentSchemaVersion: EXERCISE_CONTENT_SCHEMA_VERSION,
    payload: { tokens },
    answer: { tokenIds },
  };
}

