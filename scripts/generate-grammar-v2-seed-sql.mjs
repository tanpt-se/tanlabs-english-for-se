#!/usr/bin/env node
/**
 * Write supabase/migrations/016_grammar_v2_seed.sql from packs-v2.json.
 * Does not touch v1 rows except via 015 (unpublished). Never overwrites 008.
 *
 * Usage: pnpm run grammar:v2:seed:sql
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = process.cwd();
const PACKS_PATH = resolve(ROOT, 'supabase/seed/grammar/packs-v2.json');
const OUT_PATH = resolve(ROOT, 'supabase/migrations/016_grammar_v2_seed.sql');

const LESSON_SCHEMA = 1;
const EXERCISE_SCHEMA = 1;
const MIN_EXAMPLES = 5;
const LEVELS = new Set(['A2', 'B1', 'B2', 'C1']);

function escLiteral(value) {
  return JSON.stringify(value).replace(/'/g, "''");
}

function padId(prefix, index) {
  return `${prefix}${String(index).padStart(12, '0')}`;
}

function sqlText(value) {
  return String(value).replace(/'/g, "''");
}

function expandLesson(topicSlug, lesson, sortOrder) {
  if (!LEVELS.has(lesson.level)) {
    throw new Error(`${topicSlug}/${lesson.key}: invalid level ${lesson.level}`);
  }
  if (!lesson.title || !lesson.description) {
    throw new Error(`${topicSlug}/${lesson.key}: title and description are required`);
  }
  if (!Array.isArray(lesson.exampleSentences) || lesson.exampleSentences.length < MIN_EXAMPLES) {
    throw new Error(`${topicSlug}/${lesson.key}: need >= ${MIN_EXAMPLES} examples`);
  }
  return {
    slug: `${topicSlug}-${lesson.key}`,
    topicSlug,
    title: lesson.title,
    description: lesson.description,
    level: lesson.level,
    sortOrder,
    contentSchemaVersion: LESSON_SCHEMA,
    contentRevision: 1,
    content: {
      usage: lesson.usage,
      forms: lesson.forms,
      examples: lesson.exampleSentences.map(([context, sentence], index) => ({
        id: `ex-${index + 1}`,
        context,
        sentence,
      })),
      tips: lesson.tips,
    },
  };
}

function expandExercise(topicSlug, lessonSlugByKey, exercise, sortOrder) {
  const lessonSlug = lessonSlugByKey.get(exercise.lessonKey);
  if (!lessonSlug) {
    throw new Error(`${exercise.id}: unknown lessonKey ${exercise.lessonKey}`);
  }
  return {
    id: exercise.id,
    topicSlug,
    lessonSlug,
    type: exercise.type,
    prompt: exercise.prompt,
    explanation: exercise.explanation,
    sortOrder,
    contentSchemaVersion: EXERCISE_SCHEMA,
    payload: exercise.payload,
    answer: exercise.answer,
  };
}

const packs = JSON.parse(readFileSync(PACKS_PATH, 'utf8'));
if (!Array.isArray(packs) || packs.length === 0) {
  throw new Error('packs-v2.json must be a non-empty array');
}

const topics = [];
const lessons = [];
const exercises = [];

packs.forEach((pack, topicIndex) => {
  topics.push({
    slug: pack.slug,
    title: pack.title,
    description: pack.description,
    sortOrder: pack.sortOrder ?? topicIndex + 1,
    categorySlug: pack.categorySlug,
    curriculumVersion: pack.curriculumVersion ?? 2,
    isOptional: pack.isOptional === true,
  });

  const lessonSlugByKey = new Map();
  pack.lessons.forEach((lesson, lessonIndex) => {
    const row = expandLesson(pack.slug, lesson, lessonIndex + 1);
    lessonSlugByKey.set(lesson.key, row.slug);
    lessons.push(row);
  });

  pack.exercises.forEach((exercise, exerciseIndex) => {
    exercises.push(expandExercise(pack.slug, lessonSlugByKey, exercise, exerciseIndex + 1));
  });
});

const topicIds = Object.fromEntries(
  topics.map((topic, index) => [topic.slug, padId('b1000000-0000-4000-8000-', index + 1)]),
);
const lessonIds = Object.fromEntries(
  lessons.map((lesson, index) => [lesson.slug, padId('b2000000-0000-4000-8000-', index + 1)]),
);

const sql = [
  'begin;',
  '',
  '-- Generated by `pnpm run grammar:v2:seed:sql` from supabase/seed/grammar/packs-v2.json',
  '-- Forward-only: inserts curriculum v2. Does not delete v1 progress/attempts.',
  '',
];

for (const topic of topics) {
  sql.push('');
  sql.push(`insert into public.grammar_topics (
  id, slug, title, description, sort_order, published, category_slug, curriculum_version, is_optional
)
values (
  '${topicIds[topic.slug]}',
  '${sqlText(topic.slug)}',
  '${sqlText(topic.title)}',
  '${sqlText(topic.description)}',
  ${topic.sortOrder},
  true,
  '${sqlText(topic.categorySlug)}',
  ${topic.curriculumVersion},
  ${topic.isOptional}
)
on conflict (slug) do update set
  title = excluded.title,
  description = excluded.description,
  sort_order = excluded.sort_order,
  published = excluded.published,
  category_slug = excluded.category_slug,
  curriculum_version = excluded.curriculum_version,
  is_optional = excluded.is_optional,
  updated_at = now();`);
}

for (const lesson of lessons) {
  sql.push('');
  sql.push(`insert into public.grammar_lessons (
  id, topic_id, slug, title, description, level, content, content_schema_version, content_revision, sort_order, published
)
values (
  '${lessonIds[lesson.slug]}',
  '${topicIds[lesson.topicSlug]}',
  '${sqlText(lesson.slug)}',
  '${sqlText(lesson.title)}',
  '${sqlText(lesson.description)}',
  '${lesson.level}',
  '${escLiteral(lesson.content)}'::jsonb,
  ${lesson.contentSchemaVersion},
  ${lesson.contentRevision},
  ${lesson.sortOrder},
  true
)
on conflict (topic_id, slug) do update set
  title = excluded.title,
  description = excluded.description,
  level = excluded.level,
  content = excluded.content,
  content_schema_version = excluded.content_schema_version,
  content_revision = excluded.content_revision,
  sort_order = excluded.sort_order,
  published = excluded.published,
  updated_at = now();`);
}

exercises.forEach((exercise, index) => {
  const id = padId('b3000000-0000-4000-8000-', index + 1);
  sql.push('');
  sql.push(`insert into public.grammar_exercises (
  id, topic_id, lesson_id, exercise_key, type, prompt, payload, answer, explanation, content_schema_version, sort_order, published
)
values (
  '${id}',
  '${topicIds[exercise.topicSlug]}',
  '${lessonIds[exercise.lessonSlug]}',
  '${sqlText(exercise.id)}',
  '${exercise.type}',
  '${sqlText(exercise.prompt)}',
  '${escLiteral(exercise.payload)}'::jsonb,
  '${escLiteral(exercise.answer)}'::jsonb,
  '${sqlText(exercise.explanation)}',
  ${exercise.contentSchemaVersion},
  ${exercise.sortOrder},
  true
)
on conflict (lesson_id, exercise_key) do update set
  type = excluded.type,
  prompt = excluded.prompt,
  payload = excluded.payload,
  answer = excluded.answer,
  explanation = excluded.explanation,
  content_schema_version = excluded.content_schema_version,
  sort_order = excluded.sort_order,
  published = excluded.published,
  updated_at = now();`);
});

sql.push('');
sql.push('commit;');
sql.push('');

writeFileSync(OUT_PATH, sql.join('\n'));
console.log(
  `Wrote ${OUT_PATH} (${topics.length} topics, ${lessons.length} lessons, ${exercises.length} exercises)`,
);
