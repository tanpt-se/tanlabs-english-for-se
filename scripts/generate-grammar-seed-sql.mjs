#!/usr/bin/env node
/**
 * Bootstrap Grammar catalogs into supabase/migrations/008_grammar_seed.sql
 * from the authoring template at supabase/seed/grammar/packs.json.
 *
 * Topics are shared per grammar family; CEFR level lives on each lesson.
 * Runtime app content remains Supabase rows only — this script never ships in the bundle.
 *
 * Usage: pnpm run grammar:seed:sql
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = process.cwd();
const PACKS_PATH = resolve(ROOT, 'supabase/seed/grammar/packs.json');
const OUT_PATH = resolve(ROOT, 'supabase/migrations/008_grammar_seed.sql');

const LESSON_SCHEMA = 1;
const EXERCISE_SCHEMA = 1;
const MIN_EXAMPLES = 5;
const LEVELS = new Set(['A2', 'B1', 'B2', 'C1']);

/** @typedef {{ slug: string, title: string, description: string, sortOrder: number, lessons: LessonPack[], exercises: ExercisePack[] }} TopicPack */
/** @typedef {{ key: string, level: string, title: string, description: string, usage: string, forms: Record<string,string>, exampleSentences: [string,string][], tips: string[] }} LessonPack */
/** @typedef {{ id: string, lessonKey: string, type: string, prompt: string, explanation: string, payload: unknown, answer: unknown }} ExercisePack */

function escLiteral(value) {
  return JSON.stringify(value).replace(/'/g, "''");
}

function padId(prefix, index) {
  return `${prefix}${String(index).padStart(12, '0')}`;
}

function expandLesson(topicSlug, lesson, sortOrder) {
  if (!LEVELS.has(lesson.level)) {
    throw new Error(`${topicSlug}/${lesson.key}: invalid level ${lesson.level}`);
  }
  if (!lesson.title || !lesson.description) {
    throw new Error(`${topicSlug}/${lesson.key}: title and description are required`);
  }
  if (!Array.isArray(lesson.exampleSentences) || lesson.exampleSentences.length < MIN_EXAMPLES) {
    throw new Error(`${topicSlug}/${lesson.key}: need >= ${MIN_EXAMPLES} examples`);
  }
  return {
    slug: `${topicSlug}-${lesson.key}`,
    topicSlug,
    title: lesson.title,
    description: lesson.description,
    level: lesson.level,
    sortOrder,
    contentSchemaVersion: LESSON_SCHEMA,
    contentRevision: 1,
    content: {
      usage: lesson.usage,
      forms: lesson.forms,
      examples: lesson.exampleSentences.map(([context, sentence], index) => ({
        id: `ex-${index + 1}`,
        context,
        sentence,
      })),
      tips: lesson.tips,
    },
  };
}

function expandExercise(topicSlug, lessonSlugByKey, exercise, sortOrder) {
  const lessonSlug = lessonSlugByKey.get(exercise.lessonKey);
  if (!lessonSlug) {
    throw new Error(`${exercise.id}: unknown lessonKey ${exercise.lessonKey}`);
  }
  return {
    id: exercise.id,
    topicSlug,
    lessonSlug,
    type: exercise.type,
    prompt: exercise.prompt,
    explanation: exercise.explanation,
    sortOrder,
    contentSchemaVersion: EXERCISE_SCHEMA,
    payload: exercise.payload,
    answer: exercise.answer,
  };
}

/** @type {TopicPack[]} */
const packs = JSON.parse(readFileSync(PACKS_PATH, 'utf8'));
if (!Array.isArray(packs) || packs.length === 0) {
  throw new Error('packs.json must be a non-empty array');
}

const topics = [];
const lessons = [];
const exercises = [];

packs.forEach((pack, topicIndex) => {
  if (pack.level != null) {
    throw new Error(`${pack.slug}: topic.level is removed — put level on each lesson`);
  }
  topics.push({
    slug: pack.slug,
    title: pack.title,
    description: pack.description,
    sortOrder: pack.sortOrder ?? topicIndex + 1,
  });

  const lessonSlugByKey = new Map();
  pack.lessons.forEach((lesson, lessonIndex) => {
    const row = expandLesson(pack.slug, lesson, lessonIndex + 1);
    lessonSlugByKey.set(lesson.key, row.slug);
    lessons.push(row);
  });

  pack.exercises.forEach((exercise, exerciseIndex) => {
    exercises.push(expandExercise(pack.slug, lessonSlugByKey, exercise, exerciseIndex + 1));
  });
});

const topicIds = Object.fromEntries(
  topics.map((topic, index) => [topic.slug, padId('a1000000-0000-4000-8000-', index + 1)]),
);
const lessonIds = Object.fromEntries(
  lessons.map((lesson, index) => [lesson.slug, padId('a2000000-0000-4000-8000-', index + 1)]),
);

const sql = [
  'begin;',
  '',
  '-- Generated by `pnpm run grammar:seed:sql` from supabase/seed/grammar/packs.json',
  '-- Bootstrap only: after migrate, manage/publish content in Supabase.',
  '-- Topics are shared grammar families; CEFR level is on grammar_lessons.level.',
  '',
  'delete from public.grammar_attempts;',
  '',
  'delete from public.user_grammar_progress;',
  '',
  'delete from public.grammar_exercises;',
  '',
  'delete from public.grammar_lessons;',
  '',
  'delete from public.grammar_topics;',
  '',
  '-- Ensure CEFR lives on lessons (idempotent for DBs that lag behind 010).',
  'alter table public.grammar_lessons add column if not exists level text;',
  "update public.grammar_lessons set level = 'A2' where level is null;",
  'alter table public.grammar_lessons alter column level set not null;',
  'alter table public.grammar_lessons drop constraint if exists grammar_lessons_level_check;',
  "alter table public.grammar_lessons add constraint grammar_lessons_level_check check (level in ('A2', 'B1', 'B2', 'C1'));",
  'alter table public.grammar_topics drop constraint if exists grammar_topics_level_check;',
  'alter table public.grammar_topics drop column if exists level;',
  '',
  '-- Lesson title + description (idempotent for DBs that lag behind 011).',
  'alter table public.grammar_lessons add column if not exists title text;',
  'alter table public.grammar_lessons add column if not exists description text;',
  'alter table public.grammar_lessons drop column if exists summary;',
];

for (const topic of topics) {
  sql.push('');
  sql.push(`insert into public.grammar_topics (id, slug, title, description, sort_order, published)
values ('${topicIds[topic.slug]}', '${topic.slug}', '${topic.title.replace(
    /'/g,
    "''",
  )}', '${topic.description.replace(/'/g, "''")}', ${topic.sortOrder}, true)
on conflict (slug) do update set title = excluded.title, description = excluded.description, sort_order = excluded.sort_order, published = excluded.published, updated_at = now();`);
}

for (const lesson of lessons) {
  sql.push('');
  sql.push(`insert into public.grammar_lessons (id, topic_id, slug, title, description, level, content, content_schema_version, content_revision, sort_order, published)
values ('${lessonIds[lesson.slug]}', '${topicIds[lesson.topicSlug]}', '${
    lesson.slug
  }', '${lesson.title.replace(/'/g, "''")}', '${lesson.description.replace(/'/g, "''")}', '${
    lesson.level
  }', '${escLiteral(lesson.content)}'::jsonb, ${lesson.contentSchemaVersion}, ${
    lesson.contentRevision
  }, ${lesson.sortOrder}, true)
on conflict (topic_id, slug) do update set title = excluded.title, description = excluded.description, level = excluded.level, content = excluded.content, content_schema_version = excluded.content_schema_version, content_revision = excluded.content_revision, sort_order = excluded.sort_order, published = excluded.published, updated_at = now();`);
}

exercises.forEach((exercise, index) => {
  const id = padId('a3000000-0000-4000-8000-', index + 1);
  sql.push('');
  sql.push(`insert into public.grammar_exercises (id, topic_id, lesson_id, exercise_key, type, prompt, payload, answer, explanation, content_schema_version, sort_order, published)
values ('${id}', '${topicIds[exercise.topicSlug]}', '${lessonIds[exercise.lessonSlug]}', '${
    exercise.id
  }', '${exercise.type}', '${exercise.prompt.replace(/'/g, "''")}', '${escLiteral(
    exercise.payload,
  )}'::jsonb, '${escLiteral(exercise.answer)}'::jsonb, '${exercise.explanation.replace(
    /'/g,
    "''",
  )}', ${exercise.contentSchemaVersion}, ${exercise.sortOrder}, true)
on conflict (lesson_id, exercise_key) do update set type = excluded.type, prompt = excluded.prompt, payload = excluded.payload, answer = excluded.answer, explanation = excluded.explanation, content_schema_version = excluded.content_schema_version, sort_order = excluded.sort_order, published = excluded.published, updated_at = now();`);
});

sql.push('');
sql.push('commit;');
sql.push('');

writeFileSync(OUT_PATH, sql.join('\n'));
console.log(
  `Wrote ${OUT_PATH} (${topics.length} topics, ${lessons.length} lessons, ${exercises.length} exercises)`,
);
