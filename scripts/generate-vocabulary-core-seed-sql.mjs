#!/usr/bin/env node
/**
 * Write supabase/migrations/018_vocabulary_core_seed.sql from core-expressions.json.
 * Forward-only UPDATEs (and INSERT fallback). Never overwrites 014.
 *
 * Usage: pnpm run vocabulary:core:sql
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = process.cwd();
const CORE_PATH = resolve(ROOT, 'supabase/seed/vocabulary/core-expressions.json');
const OUT_PATH = resolve(ROOT, 'supabase/migrations/018_vocabulary_core_seed.sql');

function sqlText(value) {
  return String(value ?? '').replace(/'/g, "''");
}

function slugKey(term) {
  const base = String(term)
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 48);
  return base || 'core-item';
}

const root = JSON.parse(readFileSync(CORE_PATH, 'utf8'));
const situations = root.situations ?? [];
if (situations.length !== 5) {
  throw new Error('core-expressions.json must have 5 situations');
}

const sql = [
  'begin;',
  '',
  '-- Generated by `pnpm run vocabulary:core:sql` from core-expressions.json',
  '-- Marks 50 core expressions. Does not rewrite the 2500-term library seed.',
  '',
  'update public.vocabulary_items',
  'set is_core = false, core_order = null',
  'where is_core = true;',
  '',
];

let total = 0;
for (const situation of situations) {
  const items = situation.items ?? [];
  if (items.length !== 10) {
    throw new Error(`${situation.slug}: need 10 core items, got ${items.length}`);
  }
  items.forEach((item, index) => {
    total += 1;
    const order = item.coreOrder ?? index + 1;
    const countability = item.countability ?? 'na';
    const content = {
      patterns: item.patterns ?? [],
      examples: item.examples ?? [],
      alternatives: item.alternatives ?? [],
      notes: item.notes ?? [],
      pronunciation: item.pronunciation ?? null,
      countability,
    };
    const key = `core-${slugKey(item.term)}`;
    sql.push(`-- ${situation.slug} #${order} ${item.term}`);
    sql.push(`update public.vocabulary_items as i
set
  is_core = true,
  core_order = ${order},
  pronunciation = '${sqlText(item.pronunciation)}',
  countability = '${sqlText(countability)}',
  type = '${sqlText(item.type)}',
  meaning = '${sqlText(item.meaning)}',
  context = '${sqlText(item.context)}',
  level = '${sqlText(item.level)}',
  pos = '${sqlText(item.pos)}',
  content = coalesce(i.content, '{}'::jsonb) || '${sqlText(JSON.stringify(content))}'::jsonb,
  updated_at = now()
from public.vocabulary_situations as s
where i.situation_id = s.id
  and s.slug = '${sqlText(situation.slug)}'
  and lower(i.term) = lower('${sqlText(item.term)}');`);
    sql.push('');
    sql.push(`insert into public.vocabulary_items (
  situation_id, item_key, type, term, meaning, context, level, pos, content,
  content_schema_version, content_revision, sort_order, published,
  is_core, core_order, pronunciation, countability
)
select
  s.id,
  '${sqlText(key)}',
  '${sqlText(item.type)}',
  '${sqlText(item.term)}',
  '${sqlText(item.meaning)}',
  '${sqlText(item.context)}',
  '${sqlText(item.level)}',
  '${sqlText(item.pos)}',
  '${sqlText(JSON.stringify(content))}'::jsonb,
  1,
  1,
  ${order},
  true,
  true,
  ${order},
  '${sqlText(item.pronunciation)}',
  '${sqlText(countability)}'
from public.vocabulary_situations as s
where s.slug = '${sqlText(situation.slug)}'
  and not exists (
    select 1
    from public.vocabulary_items as i
    where i.situation_id = s.id
      and lower(i.term) = lower('${sqlText(item.term)}')
  );`);
    sql.push('');
  });
}

sql.push(`do $$
declare
  v_count integer;
begin
  select count(*) into v_count
  from public.vocabulary_items
  where is_core = true and published = true;
  if v_count <> ${total} then
    raise exception 'Expected ${total} core vocabulary items, found %', v_count;
  end if;
end
$$;`);
sql.push('');
sql.push('commit;');
sql.push('');

writeFileSync(OUT_PATH, sql.join('\n'));
console.log(`Wrote ${OUT_PATH} (${total} core expressions)`);
